-- ───────────────────────────────────────────────────────────────────────────
-- 0002 — Tabelas que o app do cliente usa e o banco não tem
--
-- Rode este script inteiro no SQL Editor do Supabase. É idempotente.
-- Pré-requisitos: 0000 e 0001.
--
-- Por quê: o código do app do cliente (customer_api/models.py) usa 6 tabelas e
-- 1 coluna que NÃO existem neste banco — ele foi criado pelo schema.sql antigo e
-- o `manage.py migrate` do boot nunca conseguiu rodar (as tabelas-base já
-- existiam; django_migrations está vazio). Sem elas, QR do veículo, documentos,
-- recuperação de senha, verificação de e-mail, bloqueio anti-força-bruta e push
-- falham em produção.
--
-- Este script cria exatamente o que os models esperam (mesmos nomes, tipos e
-- índices). Depois dele, o Django NÃO deve mais criar/alterar tabelas: veja o
-- plano (db/PLANO.md) — as tabelas passam a ser dadas por estas migrations SQL.
--
-- Tabelas novas: RLS ligada, sem policy. O app do cliente conecta como dono
-- (postgres), que ignora RLS; a chave anon/authenticated fica sem acesso.
-- ───────────────────────────────────────────────────────────────────────────

begin;

do $$
begin
  if not exists (select 1 from public.schema_migrations where versao = '0001_limpeza_segura') then
    raise exception 'Rode a 0001_limpeza_segura antes (e resolva as pendências dela).';
  end if;
  if to_regclass('public.customers') is null or to_regclass('public.customer_vehicles') is null then
    raise exception 'Faltam customers/customer_vehicles.';
  end if;
end $$;

-- customers.email_verified: cadastros que já existem são considerados verificados
-- (mesma regra da migration 0003 do Django); os novos nascem não verificados.
do $$
begin
  if not exists (select 1 from information_schema.columns
                  where table_schema = 'public' and table_name = 'customers' and column_name = 'email_verified') then
    alter table public.customers add column email_verified boolean not null default true;
    alter table public.customers alter column email_verified set default false;
  end if;
end $$;

-- ── QR do veículo ────────────────────────────────────────────────────────
create table if not exists public.vehicle_qr_links (
  id          uuid primary key default gen_random_uuid(),
  uuid        uuid not null unique default gen_random_uuid(),
  vehicle_id  uuid not null references public.customer_vehicles(id) on delete cascade,
  customer_id uuid not null references public.customers(id) on delete cascade,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz
);
create index if not exists vehicle_qr_links_vehicle_idx on public.vehicle_qr_links (vehicle_id);

-- ── Documentos do veículo ────────────────────────────────────────────────
create table if not exists public.vehicle_documents (
  id            uuid primary key default gen_random_uuid(),
  customer_id   uuid not null references public.customers(id) on delete cascade,
  vehicle_id    uuid not null references public.customer_vehicles(id) on delete cascade,
  vehicle_label text not null default '',
  type          text not null,
  title         text not null,
  file_name     text not null default '',
  expiry_date   date,
  notes         text not null default '',
  created_at    timestamptz not null default now()
);
create index if not exists vehicle_documents_customer_idx on public.vehicle_documents (customer_id);

-- ── Segurança: bloqueio anti-força-bruta ─────────────────────────────────
create table if not exists public.auth_rate_limit (
  id         bigint generated by default as identity primary key,
  bucket     text not null,
  kind       text not null,
  created_at double precision not null          -- epoch (segundos)
);
create index if not exists auth_rate_limit_bucket_kind_idx on public.auth_rate_limit (bucket, kind);

-- ── Segurança: recuperação de senha e verificação de e-mail (só o hash) ──
create table if not exists public.password_reset_tokens (
  token_hash  varchar(64) primary key,
  customer_id uuid not null references public.customers(id) on delete cascade,
  email       text not null,
  expires_at  double precision not null,        -- epoch (segundos)
  used        boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.email_verification_tokens (
  token_hash  varchar(64) primary key,
  customer_id uuid not null references public.customers(id) on delete cascade,
  email       text not null,
  expires_at  double precision not null,
  used        boolean not null default false,
  created_at  timestamptz not null default now()
);

-- ── Web Push ─────────────────────────────────────────────────────────────
create table if not exists public.push_subscriptions (
  id          uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete cascade,
  endpoint    text not null unique,
  p256dh      text not null,
  auth        text not null,
  user_agent  text not null default '',
  created_at  timestamptz not null default now()
);
create index if not exists push_subscriptions_customer_idx on public.push_subscriptions (customer_id);

-- ── Fechar o acesso direto ───────────────────────────────────────────────
do $$
declare
  r text;
  t text;
begin
  foreach t in array array['vehicle_qr_links', 'vehicle_documents', 'auth_rate_limit',
                           'password_reset_tokens', 'email_verification_tokens', 'push_subscriptions'] loop
    execute format('alter table public.%I enable row level security', t);
    foreach r in array array['anon', 'authenticated'] loop
      if exists (select 1 from pg_roles where rolname = r) then
        execute format('revoke all on public.%I from %I', t, r);
      end if;
    end loop;
    if exists (select 1 from pg_roles where rolname = 'service_role') then
      execute format('grant all on public.%I to service_role', t);
    end if;
  end loop;
end $$;

insert into public.schema_migrations (versao, descricao) values
  ('0002_tabelas_app_cliente', 'Cria vehicle_qr_links, vehicle_documents, auth_rate_limit, password_reset_tokens, email_verification_tokens, push_subscriptions e customers.email_verified')
on conflict (versao) do nothing;

commit;
